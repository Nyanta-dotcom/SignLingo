/**
 * Compiles the shared/contracts JSON Schemas into plain validator functions (Ajv standalone code).
 * The app's Content-Security-Policy forbids `new Function`, which Ajv uses when it compiles a schema at run time,
 * so the browser must get validators that were compiled here, ahead of time.
 *
 *   node scripts/gen-validators.mjs          write src/storage/validators.gen.js
 *   node scripts/gen-validators.mjs --check  exit 1 if that file is out of date with the schemas
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const schemas = resolve(here, '../../shared/contracts/schemas');
export const OUTPUT = resolve(here, '../src/storage/validators.gen.js');

const VALIDATORS = {
  validateBackup: 'backup',
  validateCurriculum: 'curriculum',
  validateModelIndex: 'model_index',
  validateModelManifest: 'model_manifest',
  validateExperimentIndex: 'experiment_index',
  validateLandmarkCapture: 'landmark_capture',
  validateExperiment: 'experiment',
};

export function generate() {
  const ajv = new Ajv2020({ allErrors: true, allowUnionTypes: true, code: { source: true, esm: true, lines: true } });
  for (const name of Object.values(VALIDATORS)) {
    ajv.addSchema(JSON.parse(readFileSync(resolve(schemas, `${name}.schema.json`), 'utf8')), name);
  }
  const raw = standaloneCode.default ? standaloneCode.default(ajv, VALIDATORS) : standaloneCode(ajv, VALIDATORS);
  // Ajv still emits `require()` for its small runtime helpers even in ESM mode; turn them into imports. The helpers
  // are CommonJS (`exports.default = fn`): depending on the bundler's interop the namespace's `default` is either the
  // function or the whole exports object, so pick the function either way.
  const code = raw.replace(
    /const (\w+) = require\("([^"]+)"\)\.default;/g,
    'import * as $1_ns from "$2";\nconst $1 = typeof $1_ns.default === "function" ? $1_ns.default : $1_ns.default.default;',
  );
  if (/require\(|new Function|eval\(/.test(code)) throw new Error('generated validators still need require/eval');
  return `// Generated by scripts/gen-validators.mjs from shared/contracts/schemas. Do not edit; run the script instead.\n/* eslint-disable */\n${code}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const code = generate();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUTPUT, 'utf8'); } catch { /* missing counts as out of date */ }
    if (current.replace(/\r\n/g, '\n') !== code) {
      console.error('src/storage/validators.gen.js is out of date: run node scripts/gen-validators.mjs');
      process.exit(1);
    }
    console.log('validators up to date');
  } else {
    writeFileSync(OUTPUT, code);
    console.log(`wrote ${OUTPUT}`);
  }
}
